import { ApiError } from "@/lib/csrf-client"

/**
 * P21-W5-C1 — تمييز 403 بوابة الخطة عن بقية عائلة الـ403.
 *
 * الخلفية: كانت صفحة التحليلات تقبل أي 403 كـ«قفل Premium»، فإيقاف
 * المنظمة (routers/auth.py:115 «حساب المنظمة موقوف أو محذوف — تواصل
 * مع الدعم») كان يُعرض للمستخدم الموقوف كدعوة ترقية — خطأ تصنيف
 * يبتلع رسالة الإيقاف الحقيقية.
 *
 * العقد: عائلة بوابات الخطة (fb_dashboard/_plan_gates.py GATE_MESSAGES
 * — الخمس كلها + سابقة v22-D4 للتسلسلات) تنتهي حصرًا بالواجهة
 * الموثقة «رقِّ خطتك»؛ وهي واجهة مثبتة بعقود الاختبار الخلفية،
 * فالاعتماد عليها هنا ليس مطابقة نص هشة بل قراءة العقد العائلي
 * نفسه. أي 403 آخر (إيقاف، صلاحيات غير كافية، مسؤول منصة) يبقى
 * خطأً حقيقيًا صادقًا بإعادة المحاولة.
 */
export function isPlanLocked(e: unknown): boolean {
  return e instanceof ApiError && e.status === 403 && e.message.endsWith("رقِّ خطتك")
}
