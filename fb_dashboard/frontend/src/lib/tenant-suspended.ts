import { ApiError } from "@/lib/csrf-client"

/**
 * W2-BOT-4 (P42-2، تدقيق 3a) — تمييز إيقاف المنظمة عن بقية عائلة الـ403.
 *
 * الخلفية: إيقاف المنظمة يرفعه حارس الجلسة نفسه
 * (fb_dashboard/routers/auth.py:115 «حساب المنظمة موقوف أو محذوف — تواصل
 * مع الدعم») — فكل نداء API للتاجر الموقوف يفشل بالرسالة ذاتها. قبل هذا
 * المصنِّف كانت صفحة التحليلات وحدها تميّز العائلة (plan-lock.ts)، وكل
 * صفحة أخرى تعرض رحلة «أعد المحاولة» المضلِّلة (إعادة المحاولة لا تنجح
 * أبدًا: الحالة على الخادم) أو أسوأ — بوابة الجلسة تعيد التوجيه إلى
 * الدخول رغم أن الدخول نفسه ينجح (حلقة).
 *
 * العقد: رسالة الإيقاف تبدأ بـ«حساب المنظمة موقوف» — واجهة مثبتة بعقود
 * الاختبار الخلفية (نفس عائلة عقد «رقِّ خطتك» في plan-lock.ts: قراءة
 * العقد العائلي لا مطابقة نص هشة). أي 403 آخر (صلاحيات، مسؤول منصة،
 * بوابة خطة) يبقى خطأً حقيقيًا بإعادة محاولة صادقة.
 */
export function isTenantSuspended(e: unknown): boolean {
  return e instanceof ApiError && e.status === 403 && e.message.includes("حساب المنظمة موقوف")
}
